#!/usr/bin/env python3
"""T194: attitude-loop (rate-setpoint break) margins, linear model vs the S91/S92 flown cells; PID model-only rows.
Writes results/stage5_s91_attbreak/model_vs_measured.md.  Host python3 + numpy only."""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import margins_models as M  # noqa: E402

OUT = os.path.join(HERE, "..", "results", "stage5_s91_attbreak", "model_vs_measured.md")
# Measured: results/stage5_s91_attbreak/README.md "Cells" table (axis, rate Hz, PM deg, GM dB, f_c Hz); 267 Hz is 800/3 (S92).
MEAS = [("roll", 400, 56.6, 22.0, 1.318), ("pitch", 400, 56.8, 22.1, 1.332), ("yaw", 400, 73.4, 34.3, 0.455),
        ("roll", 800, 57.3, 21.9, 1.319), ("pitch", 800, 58.1, 21.9, 1.311), ("yaw", 800, 73.8, 33.9, 0.454),
        ("roll", 267, 55.5, 21.8, 1.364)]
PM_TOL, GM_TOL = 10.0, 3.0


def fmt(x, f="%.1f"):
    return "-" if x is None or (isinstance(x, float) and math.isnan(x)) else f % x


def mod(L, fs, **kw):
    m = M.margins_of(L, fs, **kw)
    return m["pm_deg"], m["gm_db"], (m["crossings"][0]["f_c"] if m["crossings"] else float("nan"))


def main():
    rows = ["| axis | rate Hz | model PM | model GM | model f_c | meas PM | meas GM | meas f_c | dPM | dGM | verdict |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    nfail = 0
    for ax, hz, pm, gm, fc in MEAS:
        if ax == "yaw":
            rows.append("| yaw | %d | not modelled | - | - | %.1f | %.1f | %.3f | - | - | NOT MODELLED |" % (hz, pm, gm, fc))
            continue
        fs = 800.0 / 3 if hz == 267 else float(hz)
        mpm, mgm, mfc = mod(M.L_att_indi, fs)
        dpm, dgm = pm - mpm, gm - mgm
        ok = abs(dpm) <= PM_TOL and abs(dgm) <= GM_TOL
        nfail += not ok
        rows.append("| %s | %d | %.1f | %.1f | %.3f | %.1f | %.1f | %.3f | %+.1f | %+.1f | %s |"
                    % (ax, hz, mpm, mgm, mfc, pm, gm, fc, dpm, dgm, "PASS" if ok else "FAIL"))
    pid = ["| rate Hz | G1 | PM | GM | f_c |", "|---|---|---|---|---|"]
    for fs in (400.0, 800.0):
        for g1 in (320.0, 1757.0):
            a, b, c = mod(M.L_att_pid, fs, G1=g1)
            pid.append("| %d | %g | %s | %s | %s |" % (fs, g1, fmt(a), fmt(b), fmt(c, "%.3f")))
    hdr = """# Attitude loop at the rate-setpoint break: linear model vs measured (T194)

Generated by bench/att_model_vs_measured.py (do not edit by hand). Acceptance (GATES.md G2): |dPM| <= %g deg and |dGM| <= %g dB.

## Parameters used
- INDI: HEAD_FLIGHT in margins_models.py = meas path, K 20 (MC_INDI_K_R/K_P default 20, yaml), tau_m 0.05 (MC_INDI_ACT_TC),
  fb_lead 1 (MC_INDI_LEAD 1 x K x ACT_TC = 1), sp_lead on, att_p 8 (MC_ROLL_P = MC_PITCH_P = 8 in airframe 4040_gz_quad5in:79-80),
  att_lat 1, tau_r 0.033, gyro_fc 40 / dgyro_fc 20 (run.json IMU_GYRO_CUTOFF 40, IMU_DGYRO_CUTOFF 20). G1 cancels in the INDI loop.
  pt1.params itself contains no MC_ROLL_P / MC_*RATE_*: those come from the airframe defaults.
- PID rows: MC_ROLLRATE_P/I/D 0.03/0.06/0.0006 from airframe 4040_gz_quad5in:70-72 (= PID_DEF), att_p 8. G1 320 is the legacy PID_DEF
  value, 1757 is MC_INDI_G1_R of the flown params; both shown. No measured PID cell exists.
- Pitch is identical to roll in the model (same K, att_p; G1 cancels), so the model cannot explain a roll/pitch difference.

## Model assumptions
- Small-angle hover linearisation; the quaternion law, tilt-first yaw weight, rate limits and the 1000 rad/s^2 lead clamp are ignored.
- L_att = A_att * T_cl, A_att = att_p z^-att_lat T z/(1-z), T_cl = (K + lead) Pn / (1 + L_rate). Self-tested in bench/tests/test_att_model.py:
  1 + L_M3a(att_p) = (1 + L_rate)(1 + L_att) to 1e-9 (INDI and PID, 267/400/800 Hz); |T_cl(0.01 Hz)| = 1 within 2%% (this is how the
  Pn / G1 scaling was verified: a wrong scale would not give unity DC gain); ideal-rate-loop integrator case matches the closed form.
- The attitude controller is modelled at the rate-loop rate with att_lat = 1 sample. Source: mc_att_control runs on a vehicle_attitude
  callback (mc_att_control_main.cpp:83, :254), i.e. at the estimator attitude rate, NOT the rate-loop rate. Not modelled (sample-and-hold, S86 sec 2).
- NO OUTER LOOP: the flights had velocity/position loops closed (crossover ~0.3 Hz). The outer loop feeds back around the attitude loop
  (tilt setpoint from position error) and adds a parallel path to y. Its loop gain at f_c = 1.3 Hz is roughly (0.3/1.3)^1..2 = 0.05..0.23,
  so it can bias |L| by that fraction (0.4-2 dB) and the phase by up to ~asin(0.23) = 13 deg worst case, more likely 3-6 deg. Sign not derived.
  Yaw has an outer loop too (heading hold) at lower frequency.
- Yaw: not modelled. It needs more than a scalar effectiveness change + MC_YAW_P: MC_INDI_YAW_CUT filters (_yaw_lpf_accel/_torque/_error_lpf/
  _yaw_sp_lpf, indi_rate_control.cpp:121-127) inside the rate loop, K_Y 10, MC_YAW_WEIGHT in the attitude law; none are in L_indi.

## Result
""" % (PM_TOL, GM_TOL)
    ftr = """
Reading: the model PM is ~15 deg higher than measured at every rate (outside the 10 deg limit) while GM agrees within 3 dB (267 Hz is
at 2.9). Measured f_c is 1.32 Hz vs model 1.19 Hz. A phase deficit of ~15 deg at f_c with a higher crossover is not explained by the
outer-loop estimate alone (<= ~13 deg worst case); candidate causes: attitude loop latency/sample rate (UNVERIFIED), outer-loop path,
real attitude law. Under the acceptance rule this is an ANOMALIES.md entry, not a pass.

## UNVERIFIED
- att_lat = 1 sample and the attitude loop running at the rate-loop rate (source says vehicle_attitude callback rate).
- Magnitude and sign of the outer-loop bias (rough estimate only).
- Pn scaling checked only by DC unity gain and the algebraic identity, not against a time-domain simulation of the break.
- MC_YAW_WEIGHT, MC_INDI_YAW_CUT, MC_YAW_P effective values in the flown runs (not in pt1.params; run.json has no MC_ROLL_P/MC_YAW_*).
- Real MC_ROLL_P / MC_PITCH_P effective values in the flown runs (taken from the airframe defaults).
- Measured cells are single seed, 267 Hz cell has a hole_report FAIL (count-disagree) and no coherence.
"""
    txt = hdr + "\n".join(rows) + "\n\n### PID model-only (no measured counterpart)\n\n" + "\n".join(pid) + "\n" + ftr
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(txt)
    print("\n".join(rows)); print(); print("\n".join(pid))
    return nfail


if __name__ == "__main__":
    main()
