#include "TorqueStampTracker.hpp"

bool TorqueStampTracker::checkReceived(uint64_t timestamp)
{
	bool own = false;

	for (int i = 0; i < RING; i++) {
		if (timestamp != 0 && _ring[i] == timestamp) {
			own = true;
		}
	}

	if (!own) {
		_foreign = true;
		_own_since_foreign = 0;

	} else if (_foreign && ++_own_since_foreign >= CLEAR_COUNT) {
		_foreign = false;
	}

	return !own;
}
